def _clean(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def _opener() -> str:
    o = R.choice(OPENERS)
    if not o:
        return ""
    return o


def _phrase(text: str, opener_chance: float = 0.25) -> str:
    """Иногда добавляет нейтральное вступление, но никогда — «слушай»."""
    if R.random() < opener_chance:
        o = _opener()
        if o:
            text = o + text[0].lower() + text[1:]
    if R.random() < 0.15:
        text += R.choice(FILLERS)
    return _clean(text)


def _format(turns) -> str:
    """Собирает реплики в текст. Ответы модели закрываются маркером конца."""
    out = []
    for role, text in turns:
        if role == "Человек":
            out.append(f"Человек: {text}")
        elif role == "system":
            out.append(text if text.startswith("<|sys|>") else f"<|sys|>{text}")
        else:
            out.append(f"GIGAMOGG: {text}{END_TAG}")
    return "\n\n".join(out)


def _intent_dialogue(depth: int | None = None) -> str:
    depth = depth or R.choices([1, 2, 3, 4], [3, 4, 3, 2])[0]
    keys = R.sample(list(PERSONA), depth)
    turns = []
    for k in keys:
        qs, ans = PERSONA[k]
        turns.append(("Человек", R.choice(qs)))
        turns.append(("GIGAMOGG", _phrase(R.choice(ans))))
    return _format(turns)


def _topic_dialogue() -> str:
    name = R.choice(list(TOPICS))
    t = TOPICS[name]
    turns = [("Человек", R.choice(t["start"])), ("GIGAMOGG", _phrase(R.choice(t["facts"])))]
    for _ in range(R.randint(1, 3)):
        if R.random() < 0.45:
            q, a = R.choice(CONTEXT_FOLLOWUPS)
            turns.append(("Человек", R.choice(q)))
            turns.append(("GIGAMOGG", _phrase(R.choice(a))))
        else:
            turns.append(("Человек", R.choice(t["follow"])))
            turns.append(("GIGAMOGG", _phrase(R.choice(t["replies"]))))
    if R.random() < 0.5:
        turns.append(("Человек", R.choice(t["wrap"])))
        turns.append(("GIGAMOGG", _phrase(R.choice(t["wraps"]), 0.0)))
    return _format(turns)


def _fact_pair() -> str:
    kind = R.random()
    if kind < 0.5:
        c, cap = R.choice(CAPITALS)
        q = R.choice([f"какая столица {c}", f"столица {c}", f"назови столицу {c}"])
        a = f"{cap}."
        if R.random() < 0.4:
            a += f" Столица {c} — {cap}."
    elif kind < 0.8:
        q, a, extra = R.choice(SCIENCE)
        if R.random() < 0.5:
            a = a + " " + extra
    else:
        q, a = R.choice(UNITS)
    return _format([("Человек", R.choice([q, q + "?", q.capitalize()])),
                    ("GIGAMOGG", _phrase(a, 0.2))])


def _selfcheck_dialogue() -> str:
    """Формат самокоррекции: промах, замечание, исправление."""
    q, wrong, right = R.choice(SELFCHECK)
    return _format([
        ("Человек", q),
        ("GIGAMOGG", wrong),
        ("system", "замечание: ответ неверный"),
        ("GIGAMOGG", right),
    ])


def _math_pair(r: random.Random) -> str:
    b = r.randint(2, 20)
    ans = r.randint(2, 20)
    a = b * ans
    op = r.random()
    if op < 0.4:
        q, body = f"сколько будет {a} разделить на {b}", f"{a} / {b} = {ans}. Ответ: {ans}."
    elif op < 0.7:
        x, y = r.randint(2, 30), r.randint(2, 30)
        q, body = f"сколько будет {x} умножить на {y}", f"{x} * {y} = {x * y}. Ответ: {x * y}."
    else:
        x, y = r.randint(10, 300), r.randint(10, 300)
        q, body = f"сколько будет {x} плюс {y}", f"{x} + {y} = {x + y}. Ответ: {x + y}."
    return _format([("Человек", q), ("GIGAMOGG", body)])


def _instruct_pair() -> str:
    q, a = R.choice(INSTRUCT_PAIRS)
    return _format([("Человек", R.choice([q, q + "?", q.capitalize()])),
                    ("GIGAMOGG", _phrase(a, 0.15))])


def dialog_block(rng: random.Random | None = None) -> str:
    """Один блок диалога. Все ветки возвращают готовый текст с маркерами конца."""
    r = rng or R
    kind = r.random()
    if kind < 0.28:
        return _intent_dialogue()
    if kind < 0.45:
        return _topic_dialogue()
    if kind < 0.65:
        return _instruct_pair()
    if kind < 0.82:
        return _fact_pair()
    if kind < 0.90:
        return _selfcheck_dialogue()
    return _math_pair(r)


def build_dialogues(n: int = 40000, seed: int = 20260401) -> list[str]:
    rng = random.Random(seed)
    blocks = [dialog_block(rng) for _ in range(n)]
    blocks += _math_examples(max(2000, n // 8))
    rng.shuffle(blocks)
    return blocks


def sanitize(text: str) -> str:
    """Вычищает старые шаблоны-паразиты, если корпус собран из прежних файлов."""
    text = text.replace("Слушай, ", "").replace("слушай, ", "")
    return text


def read_books(folders=("books", ".")) -> tuple[str, list[str]]:
    """Собирает сторонние .txt как литературный корпус."""
    import glob

    files: list[str] = []
    for folder in folders:
        files += glob.glob(os.path.join(folder, "*.txt"))
        files += glob.glob(os.path.join(folder, "**", "*.txt"), recursive=True)
    seen, out, info = set(), [], []
    for f in sorted(set(files)):
        base = os.path.basename(f)
        if base in seen or base in ("data.txt", "corpus.txt", "lessons.txt", "train.txt"):
            continue
        seen.add(base)
        try:
            with open(f, encoding="utf-8", errors="ignore") as fh:
                t = fh.read()
        except OSError:
            continue
        if len(t) < 2000:
            continue
        out.append(t)
        info.append(f"{base} ({len(t):,} симв.)")
    return "\n\n".join(out), info


def build(out_path: str = "corpus.txt", n_dialogues: int = 40000, books: bool = True,
          seed: int = 20260401, verbose: bool = True) -> dict:
    blocks = build_dialogues(n_dialogues, seed)
    info: list[str] = []
    if books:
        text, info = read_books()
        if text:
            text = sanitize(text)
            parts = [p.strip() for p in text.split("\n\n") if p.strip()]
            blocks += ["\n\n".join(parts[i:i + 6]) for i in range(0, len(parts), 6)]
    R.shuffle(blocks)
    body = "\n\n---\n\n".join(b.strip() for b in blocks if b.strip()) + "\n"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(body)
    stats = dict(path=out_path, chars=len(body), blocks=len(blocks),
                 dialogues=sum("Человек:" in b for b in blocks),
                 books=info, mb=round(len(body) / 1e6, 2))
    if verbose:
        print(f"Корпус: {out_path} · {stats['mb']} МБ · {stats['blocks']:,} блоков · "
              f"{stats['dialogues']:,} диалогов")
        if info:
            print("Литература: " + ", ".join(info[:6]))
    return stats


