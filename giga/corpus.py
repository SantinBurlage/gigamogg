def _math_examples(n: int) -> list[str]:
    out = []
    for _ in range(n):
        kind = R.choice(["mul", "add", "sub", "div", "percent"])
        if kind == "mul":
            a, b = R.randint(2, 30), R.randint(2, 30)
            q = R.choice([f"сколько будет {a} умножить на {b}",
                          f"{a} * {b}", f"посчитай {a} умножить на {b}"])
            ans = a * b
            body = f"{a} * {b} = {ans}. Ответ: {ans}."
        elif kind == "add":
            a, b = R.randint(10, 400), R.randint(10, 400)
            q = R.choice([f"сколько будет {a} плюс {b}", f"{a} + {b}", f"посчитай {a} + {b}"])
            ans = a + b
            body = f"{a} + {b} = {ans}. Ответ: {ans}."
        elif kind == "sub":
            a, b = R.randint(50, 500), R.randint(1, 49)
            q = R.choice([f"сколько будет {a} минус {b}", f"{a} - {b}"])
            ans = a - b
            body = f"{a} - {b} = {ans}. Ответ: {ans}."
        elif kind == "div":
            b = R.randint(2, 20)
            ans = R.randint(2, 20)
            a = b * ans
            q = R.choice([f"сколько будет {a} разделить на {b}", f"{a} / {b}"])
            body = f"{a} / {b} = {ans}. Ответ: {ans}."
        else:
            p = R.choice([5, 10, 15, 20, 25, 50])
            a = R.choice([100, 200, 300, 400, 500, 1000])
            q = R.choice([f"сколько будет {p} процентов от {a}", f"{p}% от {a}"])
            ans = a * p // 100
            body = f"{p}% от {a} — это {ans}. Ответ: {ans}."
        out.append(_format([("Человек", q), ("GIGAMOGG", body)]))
    return out


